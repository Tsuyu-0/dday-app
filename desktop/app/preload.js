const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("api", {
  getState: () => ipcRenderer.invoke("state:get"),
  setState: (s) => ipcRenderer.send("state:set", s),
  onState: (cb) => ipcRenderer.on("state", (_e, s) => cb(s)),
  onEdit: (cb) => ipcRenderer.on("edit", (_e, id) => cb(id)),
  setSettings: (k, v) => ipcRenderer.send("settings:set", k, v),
  win: (a) => ipcRenderer.send("win", a),
  version: () => ipcRenderer.invoke("app:version"),
  openFolder: () => ipcRenderer.send("folder:open"),
  saveFile: (name, text) => ipcRenderer.invoke("file:save", name, text),
  // 펫 창
  petToken: () => ipcRenderer.invoke("pet:token"),
  onPetToken: (cb) => ipcRenderer.on("pet:token", (_e, t) => cb(t)),
  onPetSay: (cb) => ipcRenderer.on("pet:say", (_e, t) => cb(t)),
  saveImage: (d) => ipcRenderer.invoke("img:save", d),
  saveSound: (d) => ipcRenderer.invoke("snd:save", d),
  checkUpdate: () => ipcRenderer.invoke("upd:check"),
  onUpdate: (cb) => ipcRenderer.on("update", (_e, i) => cb(i)),
  openUrl: (u) => ipcRenderer.send("open:url", u),
  petOpen: (v) => ipcRenderer.send("pet:open", v),
  onNav: (cb) => ipcRenderer.on("nav", (_e, v) => cb(v)),
  onPetPoke: (cb) => ipcRenderer.on("pet:poke", () => cb()),
  petIgnore: (v) => ipcRenderer.send("pet:ignore", v),
  petDragStart: () => ipcRenderer.send("pet:dragstart"),
  petDrag: (dx, dy) => ipcRenderer.send("pet:drag", dx, dy),
  petDragEnd: () => ipcRenderer.send("pet:dragend"),
  petMenu: () => ipcRenderer.send("pet:menu"),
});
